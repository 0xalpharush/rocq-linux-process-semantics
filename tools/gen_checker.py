#!/usr/bin/env python3
"""gen_checker.py — generate an example's trusted top-level Checker.v.

Every theories/Examples/<name>/Checker.v is byte-identical up to the
example <name>: it imports the example's SourceMemImage / TargetMemImage /
Proof, ascribes [Proof.strong_universal] to [Equivalence.SPEC] for this
problem's source and target images (the trusted type check that pins the
proved theorem) and [Proof.omni_strong_universal] to
[OmniEquivalence.OMNI_SPEC] (the omni statement it is derived from),
ascribes the per-image anti-vacuity checks to
[Equivalence.IMAGE_WF] for each image (same mechanism: the module type
pins the statements, the Checker contributes only [vm_compute] proofs),
and then [Print Assumptions] on the checked closure under
a fixed [Set Printing] preamble so the assumption set can be audited.

[Print Assumptions] is a vernacular command, so a Coq functor cannot fully
absorb the file; instead this generator owns the single template and stamps
it per example, so the trusted boundary is written in exactly one place and
example 12 cannot copy-paste it wrong.

Every theories/Examples/<name>/Checker.v is GENERATED by this script and is
NOT checked in: dune builds it on demand (see theories/Examples/dune), so
the template below is the only copy and there is nothing to drift out of
sync with it.  The module ascription and the Print Assumptions audit block
are emitted verbatim — only the example name varies.

Usage:
  gen_checker.py <name> [--out FILE]
      Emit the Checker.v for example <name> to stdout (or FILE).

  gen_checker.py --verify [--examples-dir DIR]
      Check that no generated file has been checked in or left behind in
      the source tree — neither a Checker.v nor a <name>_code.v.  Both are
      dune targets, and an in-source copy of a dune target is not a
      harmless duplicate: dune refuses to run at all ("Multiple rules
      generated for ..."), so this fails the build for everyone.  Naming
      the offending path here beats decoding that message.  Exit 1 if any
      is found.

  gen_checker.py --check [--examples-dir DIR]
      Pin the trusted prefix of the emitted text: for every example whose
      Checker.v theories/Examples/dune generates, render it and require the
      legacy ascription -- `Module Checked <: Equivalence.SPEC ...` whose
      [strong_universal] is the example's own [Proof.strong_universal] --
      and its `<strong_universal>` Print Assumptions block, byte for byte,
      ahead of the omni ascription, with the five Require lines that give
      those names their meaning.  The match is on the text with Coq
      comments stripped (a `"` inside a comment is refused outright, since
      Coq keeps a comment open across a `*)` inside a string), and the
      pinned names must be live: exactly one `Module Checked` and one
      `Checked.strong_universal` up to whitespace, no `Import`/`Export`
      anywhere outside the pinned Require lines (so no `Module Import` or
      same-line `Import` either), exactly five `Require` tokens, no
      `Module` (or `Module Type`/`Declare Module`) other than the four
      the template declares -- Checked, OmniChecked, SourceWf, TargetWf
      -- so nothing local can shadow `Equivalence.SPEC` or the theorem,
      no `Load`/`Declare` (a loaded file or a plugin could bring such a
      shadow in unseen), and nothing that declares an assumption
      (`Admitted`, `Axiom`, `Parameter`, `Hypothesis`, `Variable`,
      `Conjecture`, `admit`); and each of the four audit tags is
      emitted exactly once with exactly two `Print Assumptions` between
      them, so no lookalike block can put another theorem's assumptions
      under the legacy tag.  The legacy ascription is what
      the checker relies on (the omni one sits beside it, see
      theories/Examples/PROOF_GUIDE.md section 6); the build would still be
      green if the template silently ascribed a different theorem, or the
      omni one alone, so this is asserted on the text itself.  Also
      requires the set of generated names (dune comments stripped) to
      equal the set of example directories holding a Proof.v, so an
      example that dune never checks cannot exist.  Exit 1 on any
      disagreement, naming it.
"""

import argparse
import os
import re
import sys

TEMPLATE = '''\
(* AUTO-GENERATED — DO NOT EDIT, and not checked in.  This file is stamped
   out of the template in tools/gen_checker.py; dune builds it on demand,
   see theories/Examples/dune.  To regenerate by hand, from the repo root:
     python3 tools/gen_checker.py {name} --out Checker.v *)

(** * Checker for {name} — trusted top-level check

    TRUST BOUNDARY: this file is part of the trusted specification.  It pins
    the checked theorem: the per-problem proof must provide [strong_universal]
    at exactly the type [Equivalence.SPEC] demands for this problem's
    source and target memory images (and [omni_strong_universal] at the
    type [OmniEquivalence.OMNI_SPEC] demands), each image must pass the anti-vacuity
    checks [Equivalence.IMAGE_WF] demands of it, and the theorem's
    assumptions are printed for audit (only functional_extensionality_dep
    and the PrimInt63/PrimString/PrimArray primitives are permitted). *)

From Stdlib Require Import NArith List.
From LinuxProcessSemantics.EquivalenceDefinition Require Import Equivalence OmniEquivalence.
From LinuxProcessSemantics.Examples.{name} Require SourceMemImage.
From LinuxProcessSemantics.Examples.{name} Require TargetMemImage.
From LinuxProcessSemantics.Examples.{name} Require Proof.

Module Checked <: Equivalence.SPEC SourceMemImage.Source TargetMemImage.Target.
  Definition strong_universal := LinuxProcessSemantics.Examples.{name}.Proof.strong_universal.
End Checked.

(** The same proof in the omni shape ([OmniEquivalence.OMNI_SPEC]): the
    per-problem proof ends in [omni_strong_universal] and derives
    [strong_universal] from it through [OmniEquivalence.strong_universal_iff],
    so both sealings hold of one proof. *)
Module OmniChecked <: OmniEquivalence.OMNI_SPEC SourceMemImage.Source TargetMemImage.Target.
  Definition omni_strong_universal := LinuxProcessSemantics.Examples.{name}.Proof.omni_strong_universal.
End OmniChecked.

(** The per-image anti-vacuity checks, one ascribed module per image.
    [Equivalence.IMAGE_WF] pins the statements — see the rationale there
    and on each predicate; this file contributes only the [vm_compute]
    proofs, which must be stamped per example because they compute on the
    concrete image. *)
Module SourceWf <: Equivalence.IMAGE_WF SourceMemImage.Source.
  Lemma entry_fetchable :
    Equivalence.image_entry_fetchable
      SourceMemImage.Source.loaded_segments SourceMemImage.Source.init_pc = true.
  Proof. vm_compute. reflexivity. Qed.
  Lemma phdrs_readable :
    Equivalence.image_phdrs_readable
      SourceMemImage.Source.loaded_segments SourceMemImage.Source.phdrs = true.
  Proof. vm_compute. reflexivity. Qed.
  Lemma brk_satisfiable :
    Equivalence.image_brk_satisfiable
      SourceMemImage.Source.loaded_segments = true.
  Proof. vm_compute. reflexivity. Qed.
End SourceWf.

Module TargetWf <: Equivalence.IMAGE_WF TargetMemImage.Target.
  Lemma entry_fetchable :
    Equivalence.image_entry_fetchable
      TargetMemImage.Target.loaded_segments TargetMemImage.Target.init_pc = true.
  Proof. vm_compute. reflexivity. Qed.
  Lemma phdrs_readable :
    Equivalence.image_phdrs_readable
      TargetMemImage.Target.loaded_segments TargetMemImage.Target.phdrs = true.
  Proof. vm_compute. reflexivity. Qed.
  Lemma brk_satisfiable :
    Equivalence.image_brk_satisfiable
      TargetMemImage.Target.loaded_segments = true.
  Proof. vm_compute. reflexivity. Qed.
End TargetWf.

Section __.
Set Printing All.
Set Printing Fully Qualified.
Set Printing Depth 10000000000.
Set Printing Width 2000.
Goal True.
  idtac "<strong_universal>".
  idtac "<PrintAssumptions>".
  Print Assumptions Checked.strong_universal.
  idtac "</PrintAssumptions>".
  idtac "</strong_universal>".
  idtac "<omni_strong_universal>".
  idtac "<PrintAssumptions>".
  Print Assumptions OmniChecked.omni_strong_universal.
  idtac "</PrintAssumptions>".
  idtac "</omni_strong_universal>".
Abort.
End __.
'''


def render(name):
    return TEMPLATE.format(name=name)


# The trusted prefix of every emitted Checker.v, pinned as text.  These are
# NOT derived from TEMPLATE -- that would pin nothing -- they are the shape
# the checker relies on, written out a second time so that a template edit
# that drops or rewires the legacy ascription is refused by --check.
LEGACY_ASCRIPTION = '''\
Module Checked <: Equivalence.SPEC SourceMemImage.Source TargetMemImage.Target.
  Definition strong_universal := LinuxProcessSemantics.Examples.{name}.Proof.strong_universal.
End Checked.
'''

LEGACY_AUDIT = '''\
  idtac "<strong_universal>".
  idtac "<PrintAssumptions>".
  Print Assumptions Checked.strong_universal.
  idtac "</PrintAssumptions>".
  idtac "</strong_universal>".
'''

OMNI_ASCRIPTION_HEAD = (
    "Module OmniChecked <: OmniEquivalence.OMNI_SPEC "
    "SourceMemImage.Source TargetMemImage.Target.\n")

# The Require lines that give the pinned names their meaning: without
# these, `Equivalence.SPEC` and `...Proof.strong_universal` could resolve
# to anything a local module chain provides.
REQUIRES = '''\
From Stdlib Require Import NArith List.
From LinuxProcessSemantics.EquivalenceDefinition Require Import Equivalence OmniEquivalence.
From LinuxProcessSemantics.Examples.{name} Require SourceMemImage.
From LinuxProcessSemantics.Examples.{name} Require TargetMemImage.
From LinuxProcessSemantics.Examples.{name} Require Proof.
'''

# Text that would let the pinned names mean something else, or leak an
# assumption: an Import/Export bringing a shadowing `Checked` into scope
# -- anywhere, `Module Import X.` and a same-line `End X. Import X.`
# included, which is why it is matched on the text with the pinned
# Require lines removed rather than line-anchored -- or a declaration
# that adds an assumption.
FORBIDDEN = (
    (re.compile(r"\b(Import|Export)\b"), "an Import/Export"),
    # `Load` splices another file's vernacular in (found through the
    # loadpath, so a shadowing module in any .v the build copies would
    # do) and `Declare ML Module` runs plugin code; neither shows in the
    # module census.
    (re.compile(r"\b(Load|Declare)\b"), "a Load/Declare"),
    (re.compile(r"\b(Admitted|Axioms?|admit|Parameters?|Hypothes[ie]s|"
                r"Variables?|Conjecture)\b"),
     "an Admitted/Axiom/Parameter/Hypothesis/Variable/Conjecture/admit"),
)

# Every module the template declares, in order.  Any other `Module`,
# `Module Type` or `Declare Module` is refused: Coq resolves a name to its
# LAST definition, so a local `Module Equivalence` with an empty `Module
# Type SPEC`, or a local `Module LinuxProcessSemantics...Proof`, would
# leave every pinned byte in place while the ascription checks nothing.
MODULES = ["Checked", "OmniChecked", "SourceWf", "TargetWf"]
MODULE_DECL = re.compile(r"\bModule\b(?:\s+Type)?\s+(\w+)")
REQUIRE = re.compile(r"\bRequire\b")
MODULE_CHECKED = re.compile(r"\bModule\s+Checked\b")
CHECKED_SU = re.compile(r"\bChecked\s*\.\s*strong_universal\b")

# The audit tags a consumer reads the assumption sets by, each emitted
# exactly once, and exactly two Print Assumptions between them: a
# lookalike block ahead of the pinned one would put another theorem's
# assumptions under the legacy tag first.
AUDIT_TAGS = ("<strong_universal>", "</strong_universal>",
              "<omni_strong_universal>", "</omni_strong_universal>")
PRINT_ASSUMPTIONS = re.compile(r"\bPrint\s+Assumptions\b")


def strip_coq_comments(text):
    """TEXT with every `(* ... *)` comment (nesting included) removed, so
    that pinned text hidden inside a comment does not count as present;
    None if a comment holds a `"` -- Coq lexes a string inside a comment
    and keeps the comment open across a `*)` in it, so such a comment
    could hide text this stripper would count as live.  The template's
    comments hold none."""
    out = []
    depth = 0
    i = 0
    while i < len(text):
        if text.startswith("(*", i):
            depth += 1
            i += 2
        elif depth and text.startswith("*)", i):
            depth -= 1
            i += 2
        elif depth and text[i] == '"':
            return None
        else:
            if not depth:
                out.append(text[i])
            i += 1
    return "".join(out)


def check_text(text, name):
    """Return the list of disagreements between TEXT (a rendered Checker.v
    for example NAME) and the pinned trusted prefix; empty means it holds."""
    problems = []
    live = strip_coq_comments(text)
    if live is None:
        return ["%s: a comment holds a `\"`, which can keep it open across "
                "a `*)` and hide text from Coq" % name]
    legacy = LEGACY_ASCRIPTION.format(name=name)
    if live.count(legacy) != 1:
        problems.append(
            "%s: the legacy ascription `Module Checked <: Equivalence.SPEC` "
            "of Proof.strong_universal is missing or altered" % name)
    if live.count(LEGACY_AUDIT) != 1:
        problems.append(
            "%s: the <strong_universal> Print Assumptions block of "
            "Checked.strong_universal is missing or altered" % name)
    requires = REQUIRES.format(name=name)
    if live.count(requires) != 1:
        problems.append(
            "%s: the Require lines for Equivalence and the example's "
            "Proof are missing or altered" % name)
    if len(MODULE_CHECKED.findall(live)) != 1:
        problems.append(
            "%s: `Module Checked` must occur exactly once (a second one "
            "would shadow the ascribed module)" % name)
    if len(CHECKED_SU.findall(live)) != 1:
        problems.append(
            "%s: `Checked.strong_universal` must occur exactly once (in the "
            "audit block)" % name)
    for pattern, what in FORBIDDEN:
        if pattern.search(live.replace(requires, "")):
            problems.append("%s: contains %s" % (name, what))
    for tag in AUDIT_TAGS:
        if live.count('idtac "%s".' % tag) != 1:
            problems.append(
                "%s: the audit tag %s must be emitted exactly once"
                % (name, tag))
    if len(PRINT_ASSUMPTIONS.findall(live)) != 2:
        problems.append(
            "%s: exactly two Print Assumptions are allowed (the legacy and "
            "the omni block)" % name)
    declared = MODULE_DECL.findall(live)
    if declared != MODULES:
        problems.append(
            "%s: declares modules %s where exactly %s are allowed (a local "
            "module could shadow Equivalence.SPEC or the theorem)"
            % (name, declared, MODULES))
    if len(REQUIRE.findall(live)) != 5:
        problems.append(
            "%s: must hold exactly the five pinned Require lines (a sixth "
            "could bring a shadowing Equivalence into scope)" % name)
    omni_at = live.find(OMNI_ASCRIPTION_HEAD)
    if omni_at < 0:
        problems.append(
            "%s: the omni ascription `Module OmniChecked <: "
            "OmniEquivalence.OMNI_SPEC` is missing" % name)
    elif live.find(legacy) >= 0 and live.find(legacy) > omni_at:
        problems.append(
            "%s: the legacy ascription must come before the omni one" % name)
    return problems


DUNE_RULE = re.compile(r"gen_checker\.py\s+([A-Za-z0-9_]+)\s+--out")
DUNE_COMMENT = re.compile(r";[^\n]*")


def generated_names(examples_dir):
    """The example names whose Checker.v theories/Examples/dune generates
    (a rule inside a `;` comment does not count)."""
    with open(os.path.join(examples_dir, "dune")) as f:
        return sorted(set(DUNE_RULE.findall(DUNE_COMMENT.sub("", f.read()))))


def proof_names(examples_dir):
    """The example directories holding a Proof.v."""
    return sorted(name for name in os.listdir(examples_dir)
                  if os.path.isfile(os.path.join(examples_dir, name,
                                                 "Proof.v")))


def check_examples(examples_dir):
    """All disagreements over the examples tree: the generated/proved name
    sets differ, or some rendered checker fails check_text."""
    if not os.path.isdir(examples_dir):
        sys.exit("gen_checker.py: no such directory: %s" % examples_dir)
    generated = generated_names(examples_dir)
    proved = proof_names(examples_dir)
    problems = []
    for name in sorted(set(proved) - set(generated)):
        problems.append("%s: has a Proof.v but no Checker.v rule in %s"
                        % (name, os.path.join(examples_dir, "dune")))
    for name in sorted(set(generated) - set(proved)):
        problems.append("%s: has a Checker.v rule in %s but no Proof.v"
                        % (name, os.path.join(examples_dir, "dune")))
    if not generated:
        problems.append("no Checker.v rule at all in %s"
                        % os.path.join(examples_dir, "dune"))
    for name in generated:
        problems.extend(check_text(render(name), name))
    return problems


# theories/Examples/<name>/, for every <name>, holds no file matching these:
# each is a dune target (see theories/Examples/dune).
GENERATED = ("Checker.v", "%s_code.v")


def verify_not_in_tree(examples_dir):
    if not os.path.isdir(examples_dir):
        sys.exit("gen_checker.py: no such directory: %s" % examples_dir)
    stale = []
    for name in sorted(os.listdir(examples_dir)):
        d = os.path.join(examples_dir, name)
        if not os.path.isdir(d):
            continue
        for pattern in GENERATED:
            path = os.path.join(d, pattern % name if "%s" in pattern
                                else pattern)
            if os.path.exists(path):
                stale.append(path)
    if stale:
        for path in stale:
            print("gen_checker.py: generated file in the source tree: %s"
                  % path, file=sys.stderr)
        print("gen_checker.py: %d file(s); dune generates these into _build "
              "(see theories/Examples/dune) and refuses to run while an "
              "in-source copy exists.  Delete them."
              % len(stale), file=sys.stderr)
        sys.exit(1)
    print("gen_checker.py: no generated files in the source tree")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name", nargs="?", help="example name, e.g. alloc_join_ns")
    ap.add_argument("--out", default=None,
                    help="write to FILE instead of stdout")
    ap.add_argument("--verify", action="store_true",
                    help="check no generated file is left in the source tree")
    ap.add_argument("--check", action="store_true",
                    help="pin the legacy SPEC ascription of every example's "
                         "rendered Checker.v")
    ap.add_argument("--examples-dir", default="theories/Examples",
                    help="root of the examples tree (default: %(default)s)")
    args = ap.parse_args()

    if args.verify or args.check:
        if args.name or args.out:
            sys.exit("gen_checker.py: --verify/--check take no <name>/--out")
    if args.verify:
        verify_not_in_tree(args.examples_dir)
    if args.check:
        problems = check_examples(args.examples_dir)
        for problem in problems:
            print("gen_checker.py: %s" % problem, file=sys.stderr)
        if problems:
            sys.exit(1)
        print("gen_checker.py: every generated Checker.v ascribes "
              "Proof.strong_universal to Equivalence.SPEC (%d examples)"
              % len(generated_names(args.examples_dir)))
    if args.verify or args.check:
        return

    if not args.name:
        sys.exit("gen_checker.py: give an example <name>, --verify or --check")
    text = render(args.name)
    if args.out:
        with open(args.out, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
